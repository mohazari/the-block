// Generates src/api/schema.ts from the API's Pydantic models (via `python -m app.export_schema`).
// Run `npm run gen:api` after changing server/app/schemas.py; CI fails if the output is stale.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const serverDir = resolve(here, '../../server')
const output = resolve(here, '../src/api/schema.ts')

const schema = JSON.parse(
  execFileSync('uv', ['run', '--directory', serverDir, 'python', '-m', 'app.export_schema'], {
    encoding: 'utf8',
  }),
)

// Pydantic titles every property, and a `$ref` with a sibling `default` looks like a new schema;
// the generator would turn either into a needless alias (`type BidCount = number`,
// `SortOrder1`). Keep titles on models only, and reduce refs to the bare reference.
function simplifyProperties(node) {
  if (Array.isArray(node)) return node.forEach(simplifyProperties)
  if (!node || typeof node !== 'object') return
  for (const [name, property] of Object.entries(node.properties ?? {})) {
    delete property.title
    if (property.$ref) node.properties[name] = { $ref: property.$ref }
  }
  Object.values(node).forEach(simplifyProperties)
}
simplifyProperties(schema.$defs)

const types = await compile(schema, 'Api', {
  bannerComment:
    '/* Generated by `npm run gen:api` from server/app/schemas.py. Do not edit by hand. */',
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  style: { semi: false, singleQuote: true, printWidth: 100 },
})

writeFileSync(output, types)
console.log(`Wrote ${output}`)
